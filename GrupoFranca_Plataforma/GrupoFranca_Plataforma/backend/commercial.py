def identity(value):
    value = str(value).strip()
    if '@' in value:
        return 'email:' + email_address(value)
    digits = re.sub(r'\D', '', value)
    if len(digits) in (10, 11):
        digits = '55' + digits
    return 'phone:' + digits if len(digits) >= 8 else ''


